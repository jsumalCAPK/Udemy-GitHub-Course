def add_nums(a, b):
  """Returns addition of a and b"""
  return a + b


def subtract_nums(a, b):
  """Returns subtraction of a and b"""
  return a - b


def multiply_nums(a, b):
  """Returns multiplication of a and b"""
  return a * b


def divide_nums(a, b):
  """Returns division of a and b"""
  return a / b


def power(a, b):
  """Returns a raised to the power of b"""
  return a ** b
